# Builds dist\Token Speed Monitor.exe - a self-contained single-file app.
# Node.js, the CLI, the local server and the dashboard UI are all bundled, so the
# exe runs on a machine with nothing installed and never touches the internet.
#
#   powershell -ExecutionPolicy Bypass -File scripts\build-sea.ps1
#
# Requires (dev only): npm install  ->  esbuild, postject, rcedit
$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$build = Join-Path $root "build"
$dist = Join-Path $root "dist"
$exe = Join-Path $dist "Token Speed Monitor.exe"
$bin = Join-Path $root "node_modules\.bin"
$version = "0.2.0"

Set-Location $root
New-Item -ItemType Directory -Force -Path $build, $dist | Out-Null

function Step($n, $msg) { Write-Host ""; Write-Host "[$n/5] $msg" -ForegroundColor Cyan }

# ---------------------------------------------------------------- 1/5 bundle
Step 1 "Inlining dashboard files and bundling JavaScript (esbuild)"
$uiFiles = [ordered]@{}
foreach ($name in @("index.html", "style.css", "app.js")) {
  $uiFiles[$name] = [System.IO.File]::ReadAllText("$root\app\public\$name")
}
$uiJson = $uiFiles | ConvertTo-Json -Depth 4 -Compress
[System.IO.File]::WriteAllText(
  "$root\app\embedded-ui.generated.mjs",
  "// Generated by scripts/build-sea.ps1 - do not edit, not committed.`nexport default $uiJson;`n",
  (New-Object System.Text.UTF8Encoding($false))
)
& "$bin\esbuild.cmd" "app\desktop.cjs" --bundle --platform=node --format=cjs `
  --target=node22 --outfile="$build\desktop.cjs" --log-level=error
if ($LASTEXITCODE -ne 0) { throw "esbuild failed" }

# ------------------------------------------------------------------ 2/5 icon
Step 2 "Generating application icon"
$ico = Join-Path $build "icon.ico"
if (-not (Test-Path $ico)) {
  Add-Type -AssemblyName System.Drawing
  $bmp = New-Object System.Drawing.Bitmap 64, 64
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.SmoothingMode = "AntiAlias"
  $g.Clear([System.Drawing.Color]::FromArgb(15, 23, 42))
  $brush = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 180, 84))
  $font = New-Object System.Drawing.Font("Segoe UI Symbol", 34, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
  $fmt = New-Object System.Drawing.StringFormat
  $fmt.Alignment = [System.Drawing.StringAlignment]::Center
  $fmt.LineAlignment = [System.Drawing.StringAlignment]::Center
  $g.DrawString([char]0x26A1, $font, $brush, (New-Object System.Drawing.RectangleF(0, 2, 64, 60)), $fmt)
  $icon = [System.Drawing.Icon]::FromHandle($bmp.GetHicon())
  $fs = [System.IO.File]::Create($ico); $icon.Save($fs); $fs.Close()
  $g.Dispose(); $bmp.Dispose(); $font.Dispose(); $brush.Dispose(); $icon.Dispose()
  Write-Host "      wrote $ico"
}

# ------------------------------------------------------------- 3/5 sea config
Step 3 "Writing SEA configuration"
$cfg = @{
  main                          = "$build\desktop.cjs"
  output                        = "$build\sea-prep.blob"
  disableExperimentalSEAWarning = $true
  useSnapshot                   = $false
  useCodeCache                  = $false
} | ConvertTo-Json -Depth 6
# no BOM: node reads this file with JSON.parse
[System.IO.File]::WriteAllText("$build\sea-config.json", $cfg, (New-Object System.Text.UTF8Encoding($false)))

# --------------------------------------------------------------- 4/5 blob+inject
Step 4 "Generating blob and injecting it into the Node binary"
node --experimental-sea-config "$build\sea-config.json"
if ($LASTEXITCODE -ne 0) { throw "sea-config generation failed" }
Copy-Item (Get-Command node).Source $exe -Force
& "$bin\postject.cmd" $exe NODE_SEA_BLOB "$build\sea-prep.blob" --sentinel-fuse NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2
if ($LASTEXITCODE -ne 0) { throw "postject failed" }

# ------------------------------------------------------------------ 5/5 metadata
Step 5 "Setting icon and version info"
$rcedit = Join-Path $root "node_modules\rcedit\bin\rcedit-x64.exe"
if (Test-Path $rcedit) {
  $p = Start-Process -FilePath $rcedit -NoNewWindow -PassThru -ArgumentList @(
    "`"$exe`"", "--set-icon", "`"$ico`"",
    "--set-version-string", "ProductName", "Token Speed Monitor",
    "--set-version-string", "FileDescription", "Token usage & generation speed monitor",
    "--set-version-string", "CompanyName", "Token Speed Monitor",
    "--set-file-version", "$version.0", "--set-product-version", "$version.0"
  )
  # rcedit can be slow on large binaries; never let it block the build
  if (-not $p.WaitForExit(45000)) {
    try { $p.Kill() } catch { }
    Write-Warning "rcedit timed out - continuing without icon/metadata"
  } elseif ($p.ExitCode -ne 0) {
    Write-Warning "rcedit exited with $($p.ExitCode) - icon/metadata may be missing"
  }
} else {
  Write-Warning "rcedit binary not found - skipping icon/metadata"
}

$sizeMb = [math]::Round((Get-Item $exe).Length / 1MB, 1)
Write-Host ""
Write-Host "Built: $exe  ($sizeMb MB)" -ForegroundColor Green
Write-Host "Test : `"$exe`" --cli summary --json --since 24h"
Write-Host "       `"$exe`""
